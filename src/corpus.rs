//! The language-reference corpus: the `(name, chapter, doc, signature+example)`
//! table behind editor completion, editor hover (`src/lsp.rs`) and the generated
//! `docs/reference.html` (`src/bin/gen_docs.rs`).
//!
//! One entry per callable name the runtime actually resolves. Every entry
//! mirrors something in the implementation:
//!
//!   * "Keywords"                   → `lexer::keyword_or_ident`.
//!   * "Declarations and Modifiers" → the parser's declaration layer and
//!     `Parser::skip_member_modifiers` / `at_infix_operator`'s soft-keyword set.
//!   * "Comprehensions and Ranges"  → `Parser::for_stmt`, `MAKE_RANGE` (735).
//!   * "Pattern Matching"           → `Parser::pattern` and `compiler`'s test
//!     lowering, `SISTYPE` (708) / `SMATCHERR` (709).
//!   * "Collection Constructors"    → the `MAKE_*` builtins (716–743).
//!   * "Sequence Methods"           → `host::seq_method`, `seq_slice_method`,
//!     `mut_seq_method`, `heap_method`.
//!   * "Map Methods"                → `host::map_method`, `map_read_method`,
//!     `mut_map_method`.
//!   * "String / Int / Double / Boolean Methods" → `host::string_method`,
//!     `int_method`, `double_method`, `bool_method`.
//!   * "Tuples and Records"         → `host::tuple_method`, `obj_method`.
//!   * "Function Values"            → `host::closure_method`.
//!   * "scala.math"                 → `host::math_member`, `SMATH` (736).
//!   * "Throwables"                 → `host::BUILTIN_THROWABLES` and
//!     `THROWABLE_PARENTS`.
//!   * "Operators"                  → the lexer's operator tokens and the
//!     compiler's lowering to fusevm ops / the strict numeric hook.
//!   * "Predef and Interpolation"   → `SPRINTLN` (700), `SPRINT` (701),
//!     `SFORMAT` (707), `lexer::lex_interp`, `FFI_COMPILE` (704).
//!
//! A name is documented here only if `scala` resolves it, so the language server
//! and the static reference never drift from what the runtime can run. Where the
//! behaviour diverges from Scala on the JVM, the entry says so rather than
//! describing the JVM.
//!
//! The fourth field is a signature line followed by a usage example, both
//! rendered in one `scala` code block.

